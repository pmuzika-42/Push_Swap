#include "libft.h"

int	ft_lstsize(t_list *lst)
{
	int		len;
	t_list	*temp;

	len = 0;
	temp = lst;
	while (temp != NULL)
	{
		temp = temp->next;
		len++;
	}
	return (len);
}
